"""Generate dbt source declarations from a compiled plan (#3079 D3, supersedes
the retired scripts/generate_featherbase_sources.py, deleted in #3079).

Constraints:
  - the dbt source NAME is the destination database when the plan lands in one target schema —
    existing models say `source('bronze_featherbase', 'comment')` and must keep resolving.
  - descriptions come from the source's own metadata when it has any, so regeneration never
    clobbers hand-written prose (#2209 constraint 3).
  - `_dlt_loads` carries the only freshness check: warn-only at 24h. Minutes-grade liveness is
    the control plane's job — a dead sync must not be its own only alarm.
"""
from __future__ import annotations

import pathlib
from typing import Dict, List, Optional

from .manifest import Manifest
from .selectors import CompiledPlan, Relation, table_class

HEADER = "# GENERATED by `python -m pg_md_cdc generate-dbt` (#3079) — do not hand-edit."
DLT_LOADS_DESC = "dlt load ledger — one row per landed load package (liveness backstop)."


def default_out_path(m: Manifest, repo_root: pathlib.Path) -> pathlib.Path:
    return repo_root / "dbt_runner/dbt/models" / m.source_id / f"_{m.source_id}_sources.yml"


def _prose_name(source_id: str) -> str:
    return source_id.replace("_", " ").title()


def _default_description(m: Manifest, r: Relation) -> str:
    who = _prose_name(m.source_id)
    if r.module:
        return f"{who} native table (module: {r.module})."
    return f"{who} source table ({r.schema}.{r.table})."


def _q(text: str) -> str:
    return '"' + text.replace('"', "'") + '"'


def source_name(m: Manifest, target_schemas: List[str]) -> Dict[str, str]:
    """Target schema → dbt source name. One schema keeps the bare database name (existing
    `source()` calls); several disambiguate, because two dbt sources cannot share a name."""
    if len(target_schemas) == 1:
        return {target_schemas[0]: m.destination.database}
    return {s: f"{m.destination.database}__{s}" for s in target_schemas}


def render(m: Manifest, compiled: CompiledPlan, descriptions: Optional[Dict[str, str]] = None) -> str:
    """YAML text. `descriptions` (keyed 'schema.table') overrides whatever the adapter supplied."""
    descriptions = descriptions or {}
    by_schema: Dict[str, List[Relation]] = {}
    for r in compiled.relations:
        by_schema.setdefault(r.target_schema or r.schema, []).append(r)
    schemas = sorted(by_schema)
    names = source_name(m, schemas)

    lines: List[str] = [
        HEADER,
        f"# Registration: pg_md_cdc/registrations/{m.source_id}.yml · selection {compiled.selection_hash[:12]}",
        "version: 2",
        "",
        "sources:",
    ]
    for schema in schemas:
        lines += [
            f"  - name: {names[schema]}",
            f"    database: {m.destination.database}",
            f"    schema: {schema}",
            "    description: "
            + _q(
                f"CDC mirror of {m.source_id} ({schema}); slot-based logical replication, "
                "minutes-fresh (#3079/#2839). Bronze doctrine: verbatim rows, silver fixes DQ."
            ),
            "    tables:",
        ]
        for r in sorted(by_schema[schema], key=lambda x: x.table):
            desc = descriptions.get(r.qualified) or r.description or _default_description(m, r)
            lines += [
                f"      - name: {r.table}",
                f"        description: {_q(desc)}",
                "        meta:",
                f"          table_class: {r.table_class}",
                f"          source_module: {r.module if r.module else 'null'}",
                f"          source_schema: {r.schema}",
                f"          source_table: {r.table}",
            ]
        # Liveness backstop. 24h warn is deliberate: the drain only loads when something
        # changed, so a tight window false-warns on a quiet day.
        lines += [
            "      - name: _dlt_loads",
            f"        description: {_q(DLT_LOADS_DESC)}",
            "        meta:",
            f"          table_class: {table_class(m, schema, '_dlt_loads')}",
            "          source_module: null",
            f"          source_schema: {schema}",
            "          source_table: _dlt_loads",
            "        loaded_at_field: inserted_at",
            "        freshness:",
            "          warn_after: {count: 24, period: hour}",
        ]
    return "\n".join(lines) + "\n"


def write(m: Manifest, compiled: CompiledPlan, out: pathlib.Path, descriptions=None) -> pathlib.Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(m, compiled, descriptions), encoding="utf-8")
    return out
